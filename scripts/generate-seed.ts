// Generates supabase/seed.sql from lib/data/resources.ts so the database and
// the static fallback dataset never drift. Run: npm run db:seed-sql
import { writeFileSync } from "node:fs";
import { RESOURCES } from "../lib/data/resources";

const q = (v: string | undefined | null) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const arr = (v: string[] | undefined) => (v ? `array[${v.map((x) => q(x)).join(",")}]::text[]` : "null");
const num = (v: number | undefined) => (v == null ? "null" : String(v));
const bool = (v: boolean | undefined) => (v ? "true" : "false");

const rows = RESOURCES.map(
  (r) =>
    `  (${[
      q(r.id),
      q(r.name),
      q(r.category),
      arr(r.secondaryCategories ?? []),
      arr(r.countiesServed),
      arr(r.zipCodesServed),
      q(r.address),
      q(r.phone),
      q(r.website),
      q(r.eligibilitySummary),
      q(r.applicationMethod),
      q(r.status),
      q(r.lastVerified),
      num(r.typicalAmount),
      bool(r.servesFamiliesWithChildren),
      bool(r.requiresEvictionFiling),
    ].join(", ")})`,
);

const sql = `-- AUTO-GENERATED by scripts/generate-seed.ts — do not edit by hand.
-- Demo dataset: contact details and availability must be verified with each organization.

insert into resources (
  id, name, category, secondary_categories, counties_served, zip_codes_served, address, phone,
  website, eligibility_summary, application_method, status, last_verified, typical_amount,
  serves_families_with_children, requires_eviction_filing
) values
${rows.join(",\n")}
on conflict (id) do update set
  name = excluded.name,
  category = excluded.category,
  secondary_categories = excluded.secondary_categories,
  counties_served = excluded.counties_served,
  zip_codes_served = excluded.zip_codes_served,
  address = excluded.address,
  phone = excluded.phone,
  website = excluded.website,
  eligibility_summary = excluded.eligibility_summary,
  application_method = excluded.application_method,
  status = excluded.status,
  last_verified = excluded.last_verified,
  typical_amount = excluded.typical_amount,
  serves_families_with_children = excluded.serves_families_with_children,
  requires_eviction_filing = excluded.requires_eviction_filing;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${RESOURCES.length} resources to supabase/seed.sql`);
